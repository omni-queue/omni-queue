import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';

export async function runVasto(vastoArgs: string[]) {
	const command = vastoArgs[0];
	const subcommand = vastoArgs[1];

	if ((command === 'generate' || command === 'gen') && subcommand === 'isolation') {
		await runGenerateIsolation(vastoArgs.slice(2));
		return;
	}

	printVastoUsage();
	process.exitCode = command ? 1 : 0;
}

function printVastoUsage() {
	console.log('Vasto Generator CLI');
	console.log('');
	console.log('Usage:');
	console.log('  vasto generate isolation [--dir=./src/definitions]');
}

function parseFlags(flagArgs: string[]): Record<string, string> {
	const flags: Record<string, string> = {};
	for (const arg of flagArgs) {
		const match = arg.match(/^--([^=]+)=?(.*)$/);
		if (match) flags[match[1]!] = match[2] ?? 'true';
	}
	return flags;
}

function ensureVastoRuntime(cwd: string): string {
	const dir = path.join(cwd, '.vasto', 'runtime');
	fs.mkdirSync(dir, { recursive: true });
	return dir;
}

function generateIsolationWorkerShim(): string {
	return [
		'// Auto-generated by vasto generate isolation. Do not edit.',
		"import { createRequire } from 'node:module';",
		"import { pathToFileURL } from 'node:url';",
		'',
		'const require = createRequire(import.meta.url);',
		"const workerPath = require.resolve('@vasto-queue/core/libs/isolation-worker');",
		'await import(pathToFileURL(workerPath).href);',
		'',
	].join('\n');
}

function writeTempTsconfig(cwd: string, definitionsDir: string, outDir: string): string {
	const vastoDir = path.join(cwd, '.vasto');
	fs.mkdirSync(vastoDir, { recursive: true });
	const tsconfigPath = path.join(vastoDir, 'tsconfig.gen.json');
	const relativeDefsDir = path.relative(vastoDir, definitionsDir).split(path.sep).join('/');
	const relativeOutDir = path.relative(vastoDir, outDir).split(path.sep).join('/');

	const config: Record<string, unknown> = {
		compilerOptions: {
			outDir: relativeOutDir,
			noEmit: false,
			declaration: false,
			declarationMap: false,
			emitDeclarationOnly: false,
			sourceMap: false,
		},
		include: [`${relativeDefsDir}/**/*.ts`],
	};

	if (fs.existsSync(path.join(cwd, 'tsconfig.json'))) {
		config.extends = '../tsconfig.json';
	} else {
		Object.assign(config.compilerOptions as object, {
			target: 'ES2022',
			module: 'NodeNext',
			moduleResolution: 'NodeNext',
			esModuleInterop: true,
		});
	}

	fs.writeFileSync(tsconfigPath, JSON.stringify(config, null, 2) + '\n', 'utf8');
	return tsconfigPath;
}

function runTsc(tsconfigPath: string): Promise<void> {
	return new Promise((resolve, reject) => {
		const child = spawn('npx', ['tsc', '--project', tsconfigPath], {
			cwd: path.dirname(path.dirname(tsconfigPath)),
			stdio: 'inherit',
			shell: process.platform === 'win32',
		});
		child.on('exit', (code) => {
			if (code === 0) {
				resolve();
				return;
			}
			reject(new Error(`tsc exited with code ${code ?? 'unknown'}`));
		});
		child.on('error', reject);
	});
}

export async function runGenerateIsolation(flagArgs: string[]) {
	const cwd = process.cwd();
	const flags = parseFlags(flagArgs);
	const definitionsDir = path.resolve(cwd, flags.dir ?? './src/definitions');

	if (!fs.existsSync(definitionsDir)) {
		const rel = path.relative(cwd, definitionsDir);
		console.log(`Definitions directory not found: ${definitionsDir}`);
		console.log('');
		console.log('Create your first definition file:');
		console.log('');
		console.log(`  mkdir -p ${rel}`);
		console.log('');
		console.log(`  # ${rel}/main.ts`);
		console.log("  import { defineIsolation } from '@vasto-queue/core';");
		console.log("  import { MyJob } from '../jobs/my-job';");
		console.log('');
		console.log('  export const { getRegistry, getPlugins } = defineIsolation({');
		console.log('    jobs: [MyJob],');
		console.log('    plugins: [],');
		console.log('  });');
		console.log('');
		console.log('Then re-run: vasto generate isolation');
		return;
	}

	const definitionFiles = fs
		.readdirSync(definitionsDir)
		.filter((file) => file.endsWith('.ts'))
		.map((file) => path.join(definitionsDir, file));

	if (definitionFiles.length === 0) {
		console.log(`No .ts files found in ${definitionsDir}`);
		return;
	}

	const vastoRuntimeDir = ensureVastoRuntime(cwd);
	const tsconfigPath = writeTempTsconfig(cwd, definitionsDir, vastoRuntimeDir);
	const names = definitionFiles.map((file) => path.basename(file, '.ts'));

	console.log(
		`Compiling ${definitionFiles.length} definition(s): ${names.join(', ')} -> ${path.relative(cwd, vastoRuntimeDir)}/`
	);

	try {
		await runTsc(tsconfigPath);
	} finally {
		fs.rmSync(tsconfigPath, { force: true });
	}

	const shimPath = path.join(vastoRuntimeDir, 'isolation-worker.js');
	fs.writeFileSync(shimPath, generateIsolationWorkerShim(), 'utf8');
	console.log(`Generated: ${shimPath}`);
	console.log('');
	console.log('Isolation runtime ready in .vasto/runtime/');
	console.log('');
	console.log('Use in your worker config:');
	for (const name of names) {
		console.log(`  const ${name}Modules = resolveRuntimeModules('${name}');`);
	}
}
